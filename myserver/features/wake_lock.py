"""Termux wake-lock and boot-script management."""
from __future__ import annotations

import subprocess
from pathlib import Path

from ..core import paths, helpers, ui


# ---------------------------------------------------------------------------
def acquire():
    if not helpers.command_exists("termux-wake-lock"):
        ui.warn("termux-wake-lock not available (install Termux:API).")
        return False
    helpers.run_cmd(["termux-wake-lock"])
    ui.ok("Wake lock acquired.")
    return True


def release():
    if not helpers.command_exists("termux-wake-unlock"):
        return False
    helpers.run_cmd(["termux-wake-unlock"])
    ui.info("Wake lock released.")
    return True


# ---------------------------------------------------------------------------
def install_boot_script() -> bool:
    boot = paths.HOME / ".termux/boot"
    try:
        boot.parent.mkdir(parents=True, exist_ok=True)
        boot.mkdir(exist_ok=True)
    except Exception as e:
        ui.warn(f"Could not access boot dir: {e}")
        return False

    script = boot / "start-myserver.sh"
    content = (
        "#!/data/data/com.termux/files/usr/bin/sh\n"
        "# Auto-generated by myserver.\n"
        "# Requires the Termux:Boot app to be installed.\n"
        "termux-wake-lock\n"
        f"{paths.BIN_MYSERVER} start\n"
    )
    try:
        script.write_text(content)
        script.chmod(0o755)
        ui.ok(f"Boot script ready: {script}")
        if not _termux_boot_installed():
            ui.info("Note: Install Termux:Boot from F-Droid if you want auto-start on device boot.")
        return True
    except Exception as e:
        ui.err(f"Boot script write failed: {e}")
        return False


def _termux_boot_installed() -> bool:
    if Path("/data/data/com.termux.boot").exists():
        return True
    if not helpers.command_exists("pm"):
        return False
    try:
        r = subprocess.run(
            ["pm", "list", "packages", "com.termux.boot"],
            capture_output=True,
            text=True,
            timeout=4,
        )
        return r.returncode == 0 and "com.termux.boot" in (r.stdout or "")
    except Exception:
        return False


def status():
    boot = paths.HOME / ".termux/boot/start-myserver.sh"
    if boot.exists():
        ui.ok(f"Boot script: {boot}")
    else:
        ui.warn("Boot script: not installed")
    ui.info("Termux:Boot app: " +
            ("installed" if _termux_boot_installed() else "NOT installed"))