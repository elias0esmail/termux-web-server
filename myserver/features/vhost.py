"""Virtual Host (Multi-Site) manager for Nginx (`$PREFIX/etc/nginx/conf.d/`).

Allows developers to host multiple isolated projects (Laravel, WordPress,
Nextcloud, or standard PHP) on dedicated local ports (e.g. 8081, 8082) with
framework-appropriate document roots and rewrite rules, without spawning
extra web-server processes.
"""
from __future__ import annotations

import re
from pathlib import Path

from ..core import paths, helpers, ui
from ..services import nginx

SUPPORTED_TYPES = ("php", "laravel", "wordpress", "nextcloud")


def _next_available_port(start: int = 8081) -> int:
    used = {8080, 8443, 9000, 6379, 3306, paths.LIVE_PORT}
    for info in list_sites():
        if info.get("port"):
            used.add(int(info["port"]))
    port = start
    while port < 9000:
        if port not in used and not helpers.port_in_use(port):
            return port
        port += 1
    return start


def list_sites() -> list[dict[str, str]]:
    """Return metadata for all configured virtual hosts in conf.d/."""
    if not paths.NGINX_CONFD_DIR.exists():
        return []
    sites: list[dict[str, str]] = []
    for conf in sorted(paths.NGINX_CONFD_DIR.glob("*.conf")):
        try:
            txt = conf.read_text(errors="ignore")
            port_m = re.search(r"listen\s+(\d+);", txt)
            root_m = re.search(r'root\s+"?([^";\n]+)"?;', txt)
            type_m = re.search(r"#\s*myserver-type:\s*(\S+)", txt)
            sites.append({
                "name": conf.stem,
                "port": port_m.group(1) if port_m else "?",
                "root": root_m.group(1).strip() if root_m else "?",
                "type": type_m.group(1) if type_m else "php",
                "file": str(conf),
            })
        except Exception:
            continue
    return sites


def list_cmd() -> int:
    sites = list_sites()
    if not sites:
        ui.info("No custom virtual hosts configured.")
        ui.info("Create one with: myserver site add <name> [path] [--port 8081] [--type laravel]")
        return 0
    ui.info(f"Configured Virtual Hosts ({len(sites)}):")
    for s in sites:
        print(
            f"  • {ui.C_CYAN}{s['name']:<16}{ui.C_RESET} "
            f"[{s['type']:<9}]  http://localhost:{s['port']}  →  {s['root']}"
        )
    return 0


def _build_vhost_conf(name: str, doc_root: Path, port: int, site_type: str) -> str:
    extra_rules = ""
    if site_type == "nextcloud":
        extra_rules = """\
        rewrite ^/\\.well-known/carddav /remote.php/dav/ permanent;
        rewrite ^/\\.well-known/caldav /remote.php/dav/ permanent;
        location ~ ^/(?:build|tests|config|lib|3rdparty|templates|data)(?:$|/) {
            deny all;
            return 404;
        }
"""
    return f"""\
# Auto-generated by myserver
# myserver-site: {name}
# myserver-type: {site_type}
server {{
    listen {port};
    server_name {name}.local localhost;
    root "{doc_root}";
    index index.php index.html index.htm;
    client_max_body_size 512M;

    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;

    location = /__live.js {{
        proxy_pass http://127.0.0.1:{paths.LIVE_PORT}/__live.js;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_cache off;
    }}

    location ~ ^/__live/ {{
        proxy_pass http://127.0.0.1:{paths.LIVE_PORT};
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header Connection '';
        proxy_buffering off;
        proxy_cache off;
        proxy_read_timeout 24h;
    }}

    location ~ /(?:\\.env|composer\\.(?:json|lock)|artisan)(/|$) {{
        deny all;
        return 404;
    }}
{extra_rules}
    location / {{
        try_files $uri $uri/ /index.php?$query_string;
        include {paths.LIVE_CONF_FILE};
    }}

    location ~ \\.php$ {{
        try_files $uri =404;
        include fastcgi_params;
        fastcgi_pass php_fpm;
        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
        fastcgi_read_timeout 300;
        include {paths.LIVE_CONF_FILE};
    }}

    location ~ /\\. {{
        deny all;
    }}
}}
"""


def add_site(name: str,
             project_path: str | Path | None = None,
             port: int | None = None,
             site_type: str = "php") -> bool:
    if not helpers.is_safe_identifier(name):
        ui.err("Invalid site name. Use only letters, numbers, '-' or '_'.")
        return False

    site_type = site_type.lower().strip()
    if site_type not in SUPPORTED_TYPES:
        ui.err(f"Unsupported site type '{site_type}'. Choose from: {', '.join(SUPPORTED_TYPES)}")
        return False

    if project_path:
        base_dir = Path(project_path).expanduser().resolve()
    else:
        base_dir = (paths.HTDOCS_DIR / name).resolve()

    if site_type == "laravel" and (base_dir / "public").is_dir():
        doc_root = base_dir / "public"
    else:
        doc_root = base_dir

    doc_root.mkdir(parents=True, exist_ok=True)
    if not (doc_root / "index.php").exists() and site_type == "php":
        (doc_root / "index.php").write_text(
            f"<?php echo '<h1>Site: {name} is running!</h1>'; ?>\n"
        )

    chosen_port = port if port else _next_available_port()
    if chosen_port in (8080, 8443, 9000, 6379, 3306, paths.LIVE_PORT):
        ui.err(f"Port {chosen_port} is reserved by a core service.")
        return False

    paths.NGINX_CONFD_DIR.mkdir(parents=True, exist_ok=True)
    conf_file = paths.NGINX_CONFD_DIR / f"{name}.conf"
    conf_file.write_text(_build_vhost_conf(name, doc_root, chosen_port, site_type))

    nginx.enforce_htdocs_permissions(base_dir, deep=False)
    nginx.reload()
    ui.ok(f"Virtual host '{name}' ({site_type}) configured on port {chosen_port}.")
    ui.info(f"URL      : http://localhost:{chosen_port}")
    ui.info(f"Doc Root : {doc_root}")
    return True


def remove_site(name: str) -> bool:
    if not helpers.is_safe_identifier(name):
        ui.err("Invalid site name.")
        return False
    conf_file = paths.NGINX_CONFD_DIR / f"{name}.conf"
    if not conf_file.exists():
        ui.err(f"Site '{name}' not found.")
        return False
    try:
        conf_file.unlink()
        nginx.reload()
        ui.ok(f"Virtual host '{name}' removed (project files in htdocs were kept).")
        return True
    except Exception as e:
        ui.err(f"Could not remove site: {e}")
        return False
